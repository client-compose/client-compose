// Wire types for Client Compose protocol v0. See spec/PROTOCOL.md.

export const PROTOCOL_VERSION = 0;

/** Island type -> versions the client can render. */
export type Capabilities = Record<string, number[]>;

export interface ClientContext {
  platform: string;
  appVersion: string;
  locale?: string;
  [key: string]: string | number | boolean | undefined;
}

export interface ScreenRequest {
  protocol: typeof PROTOCOL_VERSION;
  screen: string;
  params?: Record<string, string>;
  client: ClientContext;
  islands: Capabilities;
}

export interface IslandError {
  code: string;
  message?: string;
  retryable?: boolean;
}

interface IslandBase {
  key: string;
  type: string;
  version: number;
}

export type IslandEntry<P = Record<string, unknown>> =
  | (IslandBase & { status: "ok"; props: P })
  | (IslandBase & { status: "error"; error: IslandError });

export interface ScreenResponse {
  protocol: typeof PROTOCOL_VERSION;
  screen: string;
  islands: IslandEntry[];
  cache?: { maxAge: number };
}

export interface ScreenErrorResponse {
  protocol: typeof PROTOCOL_VERSION;
  error: IslandError;
}

/** Identifies one island version and its props type. Generated by codegen. */
export interface IslandDescriptor<P> {
  readonly type: string;
  readonly version: number;
  /** Type-level only; never set at runtime. */
  readonly __props?: P;
}

export interface IslandManifest {
  type: string;
  version: number;
  description?: string;
  props: Record<string, unknown>;
}

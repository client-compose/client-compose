// Wire types for Client Compose protocol v0, and the few helpers every client needs. See
// spec/PROTOCOL.md.

export const PROTOCOL_VERSION = 0;

/** Island type -> versions the client can render. */
export type Capabilities = Record<string, number[]>;

export interface ClientContext {
  platform: string;
  appVersion: string;
  locale?: string;
  [key: string]: string | number | boolean | undefined;
}

export interface ScreenRequest {
  protocol: typeof PROTOCOL_VERSION;
  screen: string;
  params?: Record<string, string>;
  client: ClientContext;
  islands: Capabilities;
}

export interface IslandError {
  code: string;
  message?: string;
  retryable?: boolean;
}

interface IslandBase {
  key: string;
  type: string;
  version: number;
}

/**
 * A string's words (spec §4.7): text with `{param}` slots, or, for a counted string, its variants,
 * keyed by `#<n>`, `#<category>` or `#*`.
 */
export type StringTemplate = string | Record<string, string>;

/** Strings by key, as an island entry or a strings response carries them. */
export type Strings = Record<string, StringTemplate>;

/** A language's plural rules: category ("one", "few"…) -> condition, CLDR syntax (spec §4.7). */
export type PluralRules = Partial<Record<"zero" | "one" | "two" | "few" | "many", string>>;

export type IslandEntry<P = Record<string, unknown>> =
  | (IslandBase & {
      status: "ok";
      props: P;
      /** The island has more pages: an opaque cursor for its next one (spec §4.5). */
      next?: string;
      /** The island's strings, in the screen's language (spec §4.7). */
      strings?: Strings;
    })
  | (IslandBase & { status: "error"; error: IslandError });

/** Describes the screen as a whole: page title, description, sharing image (spec §4). */
export interface ScreenMeta {
  title?: string;
  description?: string;
  /** Absolute URL. */
  image?: string;
}

export interface ScreenResponse {
  protocol: typeof PROTOCOL_VERSION;
  screen: string;
  islands: IslandEntry[];
  meta?: ScreenMeta;
  cache?: { maxAge: number };
  /** The language the composer answered in, when it has strings (spec §4.7). */
  locale?: string;
  /** That language's plural rules, for the islands' counted strings. */
  plurals?: PluralRules;
}

/** POST {base}/strings: the app strings, in the client's language (spec §4.7). */
export interface StringsRequest {
  protocol: typeof PROTOCOL_VERSION;
  client: ClientContext;
}

/** The app strings, the language they're in, and its plural rules (spec §4.7). */
export interface StringsResponse {
  protocol: typeof PROTOCOL_VERSION;
  locale: string;
  plurals: PluralRules;
  strings: Strings;
}

/** An island in a stream's head that's still being resolved: it follows in an island line. */
export interface PendingIsland {
  key: string;
  type: string;
  version: number;
  status: "pending";
}

/** A stream's head (spec §4.6): the screen, its islands resolved or pending. */
export interface ScreenHead extends Omit<ScreenResponse, "islands"> {
  islands: (IslandEntry | PendingIsland)[];
}

/** One line of a screen's stream (spec §4.6). */
export type ScreenStreamLine =
  ({ kind: "head" } & ScreenHead) | { kind: "island"; island: IslandEntry } | { kind: "end" };

/**
 * Resolves one island of a screen again: its next page, given the cursor from its entry's `next`,
 * or from its first page without one (spec §4.5).
 */
export interface IslandRequest {
  protocol: typeof PROTOCOL_VERSION;
  screen: string;
  /** The island's key on the screen. */
  key: string;
  /** The island version the client is showing. */
  version: number;
  /** The params the screen was requested with. */
  params?: Record<string, string>;
  client: ClientContext;
  cursor?: string;
}

/** A 200 island response: the island, alone (spec §4.5). */
export interface IslandResponse<P = Record<string, unknown>> {
  protocol: typeof PROTOCOL_VERSION;
  screen: string;
  island: IslandEntry<P>;
}

export interface ScreenErrorResponse {
  protocol: typeof PROTOCOL_VERSION;
  error: IslandError;
}

/** Identifies one island version and its props type. Generated by codegen. */
/** Each declared string's params, by key: what a client fills in (spec §2). Generated by codegen. */
export type StringParams = Readonly<Record<string, readonly string[]>>;

/**
 * Identifies one island version, its props type and, if it declares strings, its strings type `S`
 * (the `t` its component receives). Generated by codegen.
 */
export interface IslandDescriptor<P, S = unknown> {
  readonly type: string;
  readonly version: number;
  /** Its declared strings' params, by key. Absent when it declares none. */
  readonly strings?: StringParams;
  /** Type-level only; never set at runtime. */
  readonly __props?: P;
  /** Type-level only; never set at runtime. */
  readonly __strings?: S;
}

/** The app strings a client declares (spec §4.7): their params, by key. Generated by codegen. */
export interface AppStringsDescriptor<S> {
  readonly strings: StringParams;
  /** Type-level only; never set at runtime. */
  readonly __strings?: S;
}

export interface IslandManifest {
  type: string;
  version: number;
  description?: string;
  props: Record<string, unknown>;
}

// ---- Actions (spec §5) ----

/** Refers to screens: those with this id whose params include all of `params` (spec §5.3). */
export interface ScreenRef {
  screen: string;
  params?: Record<string, string>;
}

/** What a successful action changed (spec §5.3). */
export interface ActionEffects {
  /** Screens whose content may have changed. Clients reload the ones on show. */
  invalidate?: ScreenRef[];
  /** A screen to show next. Clients map it to their own routes, and may ignore it. */
  navigate?: ScreenRef;
}

/** A declared error (spec §5.3). Generated code narrows `code` and `details` per action. */
export interface DeclaredError {
  code: string;
  message?: string;
  details?: unknown;
}

export interface ActionRequest<I = unknown> {
  protocol: typeof PROTOCOL_VERSION;
  action: string;
  version: number;
  input: I;
  client: ClientContext;
  idempotencyKey?: string;
}

interface ActionResponseBase {
  protocol: typeof PROTOCOL_VERSION;
  action: string;
  version: number;
}

/** A 200 action response: the action ran, and this is its outcome. */
export type ActionResponse<R = Record<string, unknown>, E extends DeclaredError = DeclaredError> =
  | (ActionResponseBase & { status: "ok"; result: R; effects?: ActionEffects })
  | (ActionResponseBase & { status: "error"; error: E });

/** Identifies one action version and its types. Generated by codegen. */
export interface ActionDescriptor<I, R, E extends DeclaredError = DeclaredError> {
  readonly action: string;
  readonly version: number;
  /** Codes of the declared errors. */
  readonly errors: readonly string[];
  /** JSON Schema of the input (codegen subset); composers validate requests against it. */
  readonly input: Record<string, unknown>;
  /** Type-level only; never set at runtime. */
  readonly __types?: { input: I; result: R; error: E };
}

/** Whether `ref` matches a screen with this id and params (spec §5.3). */
export function screenRefMatches(
  ref: ScreenRef,
  screen: string,
  params: Record<string, string> = {},
): boolean {
  return (
    ref.screen === screen && Object.entries(ref.params ?? {}).every(([k, v]) => params[k] === v)
  );
}

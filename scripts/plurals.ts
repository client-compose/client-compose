// Generates the plural rules (spec/plurals.json) and the client fixtures that check them
// (conformance/client/plural-cases.json) from CLDR's cardinal plural rules: cldr-core's
// supplemental/plurals.json.
//
//     node scripts/plurals.ts path/to/cldr-core/supplemental/plurals.json 48.2.0
//
// Counts are whole numbers, so only the rules and their integer samples are kept. "other" has no
// rule: it's what's left.
import { readFileSync, writeFileSync } from "node:fs";

const [source, version] = process.argv.slice(2);
if (!source || !version) {
  throw new Error("usage: node scripts/plurals.ts <plurals.json> <cldr version>");
}
const cldr: unknown = JSON.parse(readFileSync(source, "utf8"));
const isRecord = (v: unknown): v is Record<string, unknown> =>
  typeof v === "object" && v !== null && !Array.isArray(v);
const supplemental = isRecord(cldr) && isRecord(cldr.supplemental) ? cldr.supplemental : {};
const cardinal = supplemental["plurals-type-cardinal"];
if (!isRecord(cardinal)) {
  throw new Error("no plurals-type-cardinal in the file");
}

const rules: Record<string, Record<string, string>> = {};
/** Language -> category -> the counts in it. */
const cases: Record<string, Record<string, number[]>> = {};

/** "2~4, 22~24, 102, …" as numbers: ranges of up to 30 numbers expanded, "…" dropped. */
function samples(text: string): number[] {
  return text
    .split(",")
    .map((s) => s.trim())
    .filter((s) => s !== "" && s !== "…")
    .flatMap((s) => {
      const [from, to] = s.split("~").map(Number);
      if (from === undefined || Number.isNaN(from)) {
        return [];
      }
      if (to === undefined) {
        return [from];
      }
      return Array.from({ length: Math.min(to - from + 1, 30) }, (_, i) => from + i);
    });
}

for (const [language, categories] of Object.entries(cardinal).sort(([a], [b]) =>
  a.localeCompare(b),
)) {
  if (!isRecord(categories)) {
    continue;
  }
  const own: Record<string, string> = {};
  for (const [key, value] of Object.entries(categories)) {
    if (typeof value !== "string") {
      continue;
    }
    const category = key.replace("pluralRule-count-", "");
    const [condition = "", ...annotations] = value.split("@");
    if (category !== "other" && condition.trim() !== "") {
      own[category] = condition.trim();
    }
    const integers = annotations.find((a) => a.startsWith("integer"));
    const counts = samples(integers?.slice("integer".length) ?? "");
    if (counts.length > 0) {
      (cases[language] ??= {})[category] = counts;
    }
  }
  rules[language] = own;
}

const header = {
  $comment: `CLDR ${version} cardinal plural rules (cldr-core supplemental/plurals.json), for whole numbers: each language's categories other than "other", which is what no rule matches. Generated by scripts/plurals.ts. Data © Unicode, Inc., under the Unicode License v3 (https://www.unicode.org/license.txt).`,
};
writeFileSync("spec/plurals.json", `${JSON.stringify({ ...header, rules }, null, 2)}\n`);
writeFileSync(
  "conformance/client/plural-cases.json",
  `${JSON.stringify(
    {
      $comment: `cases[language][category] lists counts a client evaluating the language's rules in spec/plurals.json must put in that category: CLDR ${version}'s own integer samples. Generated by scripts/plurals.ts.`,
      cases,
    },
    null,
    2,
  )}\n`,
);
console.log(`${Object.keys(rules).length} languages`);

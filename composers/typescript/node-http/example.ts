// Minimal composer on node:http.
//   node composers/typescript/node-http/example.ts
//   curl -s localhost:4000/screens/profile -d '{"protocol":0,"screen":"profile","params":{"userId":"u_1"},"client":{"platform":"web","appVersion":"1.0.0"},"islands":{"profile-header":[1,2],"post-grid":[1]}}'

import { createServer, type IncomingMessage } from "node:http";

import {
  createComposer,
  island,
  type IslandDescriptor,
  place,
  reportErrors,
  screen,
} from "@client-compose/composer";

import { createRequestListener } from "./src/index.ts";

// Stand-ins for your real backend services.
const users = {
  get: async (id: string) => ({
    id,
    name: "Ada Lovelace",
    avatar: `https://example.com/avatars/${id}.png`,
    pro: true,
  }),
};
const posts = {
  recent: async (userId: string) => [{ id: "p1", thumb: `https://example.com/${userId}/p1.jpg` }],
};

// Normally generated by @client-compose/codegen from the island manifests.
const ProfileHeaderV1: IslandDescriptor<{ displayName: string; avatarUrl: string }> = {
  type: "profile-header",
  version: 1,
};
const ProfileHeaderV2: IslandDescriptor<{
  userId: string;
  displayName: string;
  avatarUrl: string;
  badge?: string;
}> = {
  type: "profile-header",
  version: 2,
};
const PostGridV1: IslandDescriptor<{ posts: { id: string; thumbnailUrl: string }[] }> = {
  type: "post-grid",
  version: 1,
};

interface Ctx {
  viewer?: string;
}

const user = (load: <T>(key: string, fn: () => Promise<T>) => Promise<T>, id: string) =>
  load(`user:${id}`, () => users.get(id));

const headerV1 = island<{ displayName: string; avatarUrl: string }, Ctx>(
  ProfileHeaderV1,
  async ({ params, load }) => {
    const u = await user(load, params.userId);
    return { displayName: u.name, avatarUrl: u.avatar };
  },
);

const headerV2 = island(ProfileHeaderV2, async ({ params, load }) => {
  const u = await user(load, params.userId);
  return {
    userId: u.id,
    displayName: u.name,
    avatarUrl: u.avatar,
    badge: u.pro ? "PRO" : undefined,
  };
});

const postGrid = island(PostGridV1, async ({ params }) => ({
  posts: (await posts.recent(params.userId)).map((p) => ({ id: p.id, thumbnailUrl: p.thumb })),
}));

const profile = screen<Ctx>("profile", {
  islands: [
    place("header", [headerV1, headerV2], { required: true }),
    place("posts", postGrid, { timeoutMs: 500 }),
  ],
  cache: { maxAge: 30 },
});

const composer = createComposer<Ctx, IncomingMessage>({
  screens: [profile],
  context: (req) => {
    const viewer = req.headers["x-user-id"];
    return { viewer: typeof viewer === "string" ? viewer : undefined };
  },
  use: [reportErrors((failure) => console.error(`${failure.kind} failed`, failure))],
});

createServer(createRequestListener(composer)).listen(4000, () =>
  console.log("composer listening on http://localhost:4000"),
);
